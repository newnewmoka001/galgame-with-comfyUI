/**
 * promptGuards.js —— 提示词里的**通用护栏片段**（唯一真源）。
 *
 * ── 为什么要有这个文件 ───────────────────────────────────
 * 提示词里为了说清"要什么风格"，几乎每个模块都会给几个「例：…」。
 * 实测的失败模式是：**模型把示例当候选池**，直接照抄进产出，于是
 *   · 论坛帖主名字反复撞车（`forumAlias.js` 早已为此单独加了护栏）；
 *   · 小镇委托标题整批都是「庭院除草」「陪酒三杯」；
 *   · 地图 POI 店名到处是「班味清零汤」「续命一刻」。
 * 这属于用户口中的「**把参考例句当作固定演出**」。
 *
 * 护栏文案本身**只该有一份**：同一句话在两三个模块里各写一遍，
 * 改一处漏一处（项目红线 8）。故抽到这里，由各提示词按需拼入。
 *
 * ⚠ 本文件不得出现任何世界观专名（引擎红线 12）—— 它只是一句通用纪律。
 */

/**
 * 「示例只是示范，不是候选池」的通用护栏。
 *
 * 用法：把返回值拼在**给出示例之后**、或放在提示词末尾的硬性要求区。
 * @param {string} [kind] - 被示例的对象（如"店名""标题""网名"），用于把话说具体
 * @returns {string}
 */
export function exampleNotCandidateGuard(kind = '内容') {
  const k = String(kind || '内容').trim() || '内容';
  return `★ 上面给出的「例：…」只是示范**风格**用的，不是候选池 —— `
    + `严禁直接照抄、也不许换个标点就当自己的${k}。必须结合当前情境**另想一个新的**。`;
}

/**
 * 「同批内不得互相重复」的通用护栏。
 *
 * 与 `exampleNotCandidateGuard` 是两件事：那条管"别抄示例"，这条管"别抄同批的同伴"。
 * @param {string} [kind] - 被约束的对象
 * @returns {string}
 */
export function noIntraBatchRepeatGuard(kind = '内容') {
  const k = String(kind || '内容').trim() || '内容';
  return `★ 同一批次内，各条目的${k}必须**互不相同**，包括近义改写与换词重述；换汤不换药同样算重复。`;
}